"""SQL execution in a killable worker process.

DuckDB's ``interrupt()`` is not always honoured promptly (observed: a query generated by
the tool agent ran for hours past its timeout). For SQL that a model wrote — the tool
agent's ``run_sql`` and the scoring of SQL-arm answers — a hard guarantee is needed: the
query runs in a persistent worker process; if it exceeds the timeout, the process is
killed and a fresh worker is started for the next query.
"""

from __future__ import annotations

import multiprocessing as mp
import queue

from . import paths


def _serve(db: str, inq, outq) -> None:
    import duckdb
    con = duckdb.connect(db, read_only=True)
    con.execute("SET enable_progress_bar = false")
    while True:
        job = inq.get()
        if job is None:
            return
        sql, search_path, cap = job
        try:
            con.execute(f"SET search_path = '{search_path}'")
            cur = con.execute(sql)
            cols = [d[0] for d in cur.description]
            rows = cur.fetchmany(cap)
            outq.put(("ok", cols, rows))
        except Exception as exc:  # noqa: BLE001
            outq.put(("err", f"{type(exc).__name__}: {str(exc)[:400]}", None))


class SQLWorker:
    def __init__(self, db: str | None = None):
        self.db = str(db or paths.DB)
        self.ctx = mp.get_context("spawn")
        self._start()

    def _start(self) -> None:
        self.inq, self.outq = self.ctx.Queue(), self.ctx.Queue()
        self.proc = self.ctx.Process(target=_serve, args=(self.db, self.inq, self.outq), daemon=True)
        self.proc.start()

    def run(self, sql: str, *, search_path: str = paths.SCHEMA, timeout_s: float = 30.0,
            cap: int = 5_000_000):
        """-> (ok, columns | error, rows)"""
        self.inq.put((sql, search_path, cap))
        try:
            return self.outq.get(timeout=timeout_s)
        except queue.Empty:
            self.proc.kill()
            self.proc.join(5)
            self._start()
            return ("err", "timeout", None)

    def close(self) -> None:
        try:
            self.inq.put(None)
            self.proc.join(5)
        finally:
            if self.proc.is_alive():
                self.proc.kill()


_W: SQLWorker | None = None


def worker() -> SQLWorker:
    global _W
    if _W is None or not _W.proc.is_alive():
        _W = SQLWorker()
    return _W
