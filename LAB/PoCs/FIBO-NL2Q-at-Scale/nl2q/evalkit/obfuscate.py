"""FIBEN-Obfuscated (specification §4.1): the same data and ontology under opaque legacy
names, to separate semantic grounding from memorization of the public FIBEN schema.

* Tables become ``TBL_C001``..``TBL_C152`` in a seeded order (so the number says nothing
  about the hierarchy); columns become ``ATTR_01``.. per table; constraint names
  ``FK_0001``... The map is written to ``artifacts/eval/obfuscated/name_map.json``. It is
  the *key*: no arm's prompt may read it.
* The data is not copied: ``<instance>_OBF`` holds views that rename ``<instance>``'s
  tables and columns, for Base and V1-V6.
* The R2RML mapping and ``db-metadata.json`` are regenerated by renaming the v1 ones.
  The ontology is unchanged (``L1`` keeps its catalog; ``L0`` loses the name signal), and
  so are the individuals' IRIs, so gold SPARQL answers are identical by construction.
* Gold SQL is rewritten through the map (sqlglot, columns qualified first).

Checks: the renamed mapping passes the R2RML conformance rules (``check_mappings.py`` of
the SPARQL-2-SQL PoC, M01-M12) against the renamed metadata; every rewritten gold SQL
returns the same answer signature as the original, on every instance.

    python -m nl2q.evalkit.obfuscate
"""

from __future__ import annotations

import importlib.util
import json
import random
import re
import sys

import sqlglot
from rdflib import RDF, Graph, Literal, Namespace
from sqlglot import exp
from sqlglot.optimizer.qualify import qualify

from .. import paths, schema
from ..compare import signature
from .gate1 import present_instances

OUT = paths.ARTIFACTS / "eval" / "obfuscated"
SEED = 20261027
RR = Namespace("http://www.w3.org/ns/r2rml#")
OBF = f"{paths.SCHEMA}_OBF"


def name_map(s: schema.Schema | None = None) -> dict:
    s = s or schema.load()
    order = sorted(s.tables)
    random.Random(SEED).shuffle(order)
    tables = {t: f"TBL_C{i:03d}" for i, t in enumerate(order, 1)}
    columns = {t: {c.name: f"ATTR_{j:02d}" for j, c in enumerate(s.tables[t].columns, 1)} for t in s.tables}
    fks = sorted(f.name for t in s.tables.values() for f in t.fks)
    return {"tables": tables, "columns": columns, "constraints": {n: f"FK_{i:04d}" for i, n in enumerate(fks, 1)}}


# ----------------------------------------------------------------------------- database
def build_views(con, src: str, m: dict) -> None:
    dst = f"{src}_OBF"
    con.execute(f'CREATE SCHEMA IF NOT EXISTS "{dst}"')
    for t, nt in m["tables"].items():
        cols = ", ".join(f'"{c}" AS "{nc}"' for c, nc in m["columns"][t].items())
        con.execute(f'CREATE OR REPLACE VIEW "{dst}"."{nt}" AS SELECT {cols} FROM "{src}"."{t}"')


def ddl(m: dict, s: schema.Schema | None = None) -> str:
    """The obfuscated DDL an L0 arm would be shown."""
    s = s or schema.load()
    out = []
    for t in sorted(s.tables, key=lambda x: m["tables"][x]):
        T = s.tables[t]
        cm = m["columns"][t]
        cols = [f'  {cm[c.name]} {c.sql_type}{"" if c.nullable else " NOT NULL"}' for c in T.columns]
        cols.append(f"  PRIMARY KEY ({', '.join(cm[k] for k in T.pk)})")
        out.append(f"CREATE TABLE {m['tables'][t]} (\n" + ",\n".join(cols) + "\n);")
    for T in s.tables.values():
        for f in T.fks:
            out.append(f"ALTER TABLE {m['tables'][T.name]} ADD CONSTRAINT {m['constraints'][f.name]} "
                       f"FOREIGN KEY ({m['columns'][T.name][f.column]}) REFERENCES "
                       f"{m['tables'][f.ref_table]} ({m['columns'][f.ref_table][f.ref_column]});")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------------------- mapping
def _q(x: str) -> str:
    return f'"{x}"'


def mapping(m: dict) -> Graph:
    g = Graph()
    g.parse(paths.MAPPING_TTL, format="turtle")
    for prefix, ns in Graph().parse(paths.MAPPING_TTL, format="turtle").namespaces():
        g.bind(prefix, ns)
    for tm in list(g.subjects(RDF.type, RR.TriplesMap)):
        lt = g.value(tm, RR.logicalTable)
        old = str(g.value(lt, RR.tableName))
        table = old.split(".")[-1].strip('"')
        cmap = m["columns"][table]
        g.set((lt, RR.tableName, Literal(f"{_q(OBF)}.{_q(m['tables'][table])}")))
        term_maps = [g.value(tm, RR.subjectMap)] + [g.value(p, RR.objectMap)
                                                    for p in g.objects(tm, RR.predicateObjectMap)]
        for node in term_maps:
            col = g.value(node, RR.column)
            if col is not None:
                g.set((node, RR.column, Literal(_q(cmap[str(col).strip('"')]), datatype=col.datatype)))
            tpl = g.value(node, RR.template)
            if tpl is not None:
                new = re.sub(r'\{"(\w+)"\}', lambda mm: '{"' + cmap[mm.group(1)] + '"}', str(tpl))
                g.set((node, RR.template, Literal(new)))
    return g


def db_metadata(m: dict) -> dict:
    meta = json.loads(paths.DB_METADATA.read_text(encoding="utf-8"))
    un = lambda x: x.strip('"')  # noqa: E731

    def rel(r: list[str]) -> list[str]:
        return [_q(OBF), _q(m["tables"][un(r[1])])]

    for r in meta["relations"]:
        t = un(r["name"][1])
        cm = m["columns"][t]
        r["name"] = rel(r["name"])
        for u in r["uniqueConstraints"]:
            u["name"] = f"{m['tables'][t]}_pkey"
            u["determinants"] = [_q(cm[un(c)]) for c in u["determinants"]]
        for c in r["columns"]:
            c["name"] = _q(cm[un(c["name"])])
        for fk in r["foreignKeys"]:
            ft, tt = un(fk["from"]["relation"][1]), un(fk["to"]["relation"][1])
            fk["name"] = m["constraints"][fk["name"]]
            fk["from"] = {"relation": rel(fk["from"]["relation"]),
                          "columns": [_q(m["columns"][ft][un(c)]) for c in fk["from"]["columns"]]}
            fk["to"] = {"relation": rel(fk["to"]["relation"]),
                        "columns": [_q(m["columns"][tt][un(c)]) for c in fk["to"]["columns"]]}
    return meta


def conformance(mapping_path, metadata_path) -> dict:
    tool = paths.ROOT.parent / "SPARQL-2-SQL" / "tools" / "check_mappings.py"
    spec = importlib.util.spec_from_file_location("check_mappings", tool)
    cm = sys.modules.get("check_mappings") or importlib.util.module_from_spec(spec)
    if "check_mappings" not in sys.modules:
        sys.modules["check_mappings"] = cm
        spec.loader.exec_module(cm)
    g = Graph().parse(mapping_path, format="turtle")
    findings = cm.check(g, cm.load_metadata(metadata_path), cm.load_tbox(paths.ONTOLOGY_TTL))
    return {"errors": sum(f.severity == "error" for f in findings),
            "warnings": sum(f.severity == "warning" for f in findings),
            "rules": sorted({f.rule for f in findings if f.severity != "info"})}


# ----------------------------------------------------------------------------- gold SQL
def _qualify_schema(s: schema.Schema) -> dict:
    return {paths.SCHEMA: {t: {c.name: c.duck_type for c in T.columns} for t, T in s.tables.items()}}


def rewrite_sql(sql: str, m: dict, s: schema.Schema | None = None, target: str = OBF) -> str:
    s = s or schema.load()
    tree = qualify(sqlglot.parse_one(sql, read="duckdb"), schema=_qualify_schema(s), dialect="duckdb",
                   db=paths.SCHEMA, quote_identifiers=True, validate_qualify_columns=False)
    # qualify() lower-cases identifiers (DuckDB is case-insensitive): match on upper case
    alias_of: dict[str, str] = {}
    for t in tree.find_all(exp.Table):
        if t.name.upper() in m["tables"]:
            alias_of[t.alias_or_name] = t.name.upper()
    for c in tree.find_all(exp.Column):
        t = alias_of.get(c.table)
        if t and c.name.upper() in m["columns"][t]:
            c.set("this", exp.to_identifier(m["columns"][t][c.name.upper()], quoted=True))
    for t in tree.find_all(exp.Table):
        if t.name.upper() in m["tables"]:
            alias = t.alias_or_name
            t.set("this", exp.to_identifier(m["tables"][t.name.upper()], quoted=True))
            t.set("db", exp.to_identifier(target, quoted=True))
            if not t.alias:
                t.set("alias", exp.TableAlias(this=exp.to_identifier(alias, quoted=True)))
    left = [t.name for t in tree.find_all(exp.Table) if t.name.upper() in m["tables"]]
    if left:
        raise ValueError(f"unrenamed tables: {left}")
    return tree.sql(dialect="duckdb")


def _answer(con, sql: str, search_path: str):
    con.execute(f"SET search_path = '{search_path}'")    # some FIBEN gold names no schema
    cur = con.execute(sql)
    sig = signature(cur.fetchall(), len(cur.description))
    return sig.ncols, sig.count, tuple(sig.col_digests), sig.row_digest   # the answer, not the row order


def _unlimited(sql: str) -> str | None:
    tree = sqlglot.parse_one(sql, read="duckdb")
    if not tree.args.get("limit"):
        return None
    tree.set("limit", None)
    return tree.sql(dialect="duckdb")


def verify_gold(con, m: dict, instances: list[str]) -> dict:
    """Same answer on every instance. A difference under ``LIMIT`` that disappears without
    it is a tie broken differently (the gold itself is order-dependent there): ``ties``. A
    gold query that itself returns the renamed query's answer on a re-run is ``unstable_gold``."""
    rows = json.loads((paths.GOLD_DIR / "gold_sql.json").read_text(encoding="utf-8"))
    from ..vkg import retarget
    res = {"queries": 0, "rewrite_errors": [], "mismatches": [], "ties": [], "unstable_gold": [],
           "both_error": 0}
    s = schema.load()
    for r in rows:
        if str(r.get("ok")) != "True":
            continue
        res["queries"] += 1
        try:
            obf = rewrite_sql(r["duck_sql"], m, s)
        except Exception as exc:  # noqa: BLE001
            res["rewrite_errors"].append({"sql_id": r["sql_id"], "error": str(exc)[:200]})
            continue
        for inst in instances:
            orig = r["duck_sql"] if inst == paths.SCHEMA else retarget(r["duck_sql"], inst)
            mine = obf.replace(f'"{OBF}"', f'"{inst}_OBF"')
            try:
                sa = _answer(con, orig, inst)
            except Exception:  # noqa: BLE001
                sa = None
            try:
                sb = _answer(con, mine, f"{inst}_OBF")
            except Exception as exc:  # noqa: BLE001
                if sa is None:
                    res["both_error"] += 1
                else:
                    res["mismatches"].append({"sql_id": r["sql_id"], "instance": inst, "error": str(exc)[:200]})
                continue
            if sa == sb:
                continue
            ua, ub = _unlimited(orig), _unlimited(mine)
            if sa is not None and ua and _answer(con, ua, inst) == _answer(con, ub, f"{inst}_OBF"):
                res["ties"].append({"sql_id": r["sql_id"], "instance": inst})
            elif sa is not None and sb in {_answer(con, orig, inst) for _ in range(20)}:
                # a tie inside a subquery: the original itself gives the renamed query's answer
                # on some runs
                res["unstable_gold"].append({"sql_id": r["sql_id"], "instance": inst})
            else:
                res["mismatches"].append({"sql_id": r["sql_id"], "instance": inst})
    con.execute("SET search_path = 'main'")
    return res


def build(verify: bool = True) -> dict:
    from ..load_fiben import connect
    s = schema.load()
    m = name_map(s)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "name_map.json").write_text(json.dumps(m, indent=1), encoding="utf-8")
    (OUT / "FIBEN_OBF.sql").write_text(ddl(m, s), encoding="utf-8")
    mapping(m).serialize(OUT / "fiben-mapping-obf.r2rml.ttl", format="turtle")
    (OUT / "db-metadata-obf.json").write_text(json.dumps(db_metadata(m), indent=1), encoding="utf-8")
    rows = json.loads((paths.GOLD_DIR / "gold_sql.json").read_text(encoding="utf-8"))
    gold_obf = {}
    for r in rows:
        if str(r.get("ok")) == "True":
            gold_obf[r["sql_id"]] = rewrite_sql(r["duck_sql"], m, s)
    (OUT / "gold_sql_obf.json").write_text(json.dumps(gold_obf, indent=1), encoding="utf-8")
    con = connect(read_only=False)
    instances = present_instances(con)
    for inst in instances:
        build_views(con, inst, m)
    out = {"tables": len(m["tables"]), "columns": sum(map(len, m["columns"].values())),
           "instances": [f"{i}_OBF" for i in instances],
           "conformance_v1": conformance(paths.MAPPING_TTL, paths.DB_METADATA),
           "conformance_obf": conformance(OUT / "fiben-mapping-obf.r2rml.ttl", OUT / "db-metadata-obf.json")}
    if verify:
        out["gold"] = verify_gold(con, m, instances)
    (OUT / "check.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    return out


if __name__ == "__main__":
    o = build()
    g = o.get("gold", {})
    print(json.dumps({k: v for k, v in o.items() if k != "gold"}, indent=1))
    print(f"gold: {g.get('queries')} queries x {len(o['instances'])} instances; "
          f"rewrite errors {len(g.get('rewrite_errors', []))}, mismatches {len(g.get('mismatches', []))}, "
          f"ties under LIMIT {len(g.get('ties', []))}, unstable gold {len(g.get('unstable_gold', []))}, "
          f"error on both {g.get('both_error')}")
