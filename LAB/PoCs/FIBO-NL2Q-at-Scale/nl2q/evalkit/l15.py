"""``L1.5`` (T-Views): SQL views that pre-flatten every class hierarchy (specification §2).

The arm writes SQL like ``L1`` but over views in which the taxonomy is already resolved,
so ``L1.5 - L1`` measures taxonomic reasoning and ``L2 - L1.5`` the change of query
language and Ontop route. For every table ``T`` the view ``<instance>_L15.T`` has:

* ``T``'s own columns;
* every non-key column of ``T``'s ancestors, joined on the shared key (a ListedSecurity
  row carries ``ISTRADEDON`` and ``ISPROVIDEDBY`` from SECURITY);
* when ``T`` has subclasses: ``SUBCLASSES``, the comma-separated names of every subclass
  the individual belongs to, and the subclasses' own columns. ``ElementOfFinancialStatement``
  becomes the union of its 8 subclass tables, ``Disclosure`` of its 118.

Views are built on every instance (Base and V1-V6) so answers can be suite-scored, and
are checked: each view has its table's row count, and each subclass's membership count in
``SUBCLASSES`` equals that subclass table's row count.

    python -m nl2q.evalkit.l15           # builds <instance>_L15 schemas, writes artifacts/eval/l15/
"""

from __future__ import annotations

import json

from .. import paths, schema, vkg_build
from .gate1 import present_instances
from .v6 import Hierarchy

OUT = paths.ARTIFACTS / "eval" / "l15"


def _q(x: str) -> str:
    return f'"{x}"'


def view_sql(h: Hierarchy, table: str, src: str) -> str:
    s = h.s
    t = s.tables[table]
    pk = t.pk[0]
    cols = [f"t.{_q(c.name)}" for c in t.columns]
    seen = {c.name for c in t.columns}
    joins = []
    for i, a in enumerate(h.ancestors(table)):
        at = s.tables[a]
        joins.append(f"LEFT JOIN {_q(src)}.{_q(a)} a{i} ON a{i}.{_q(at.pk[0])} = t.{_q(pk)}")
        for c in at.columns:
            if c.name not in seen and c.name not in at.pk:
                cols.append(f"a{i}.{_q(c.name)}")
                seen.add(c.name)
    desc = sorted(h.subtree(table) - {table})
    if desc:
        extra = sorted({c.name for d in desc for c in s.tables[d].columns
                        if c.name not in s.tables[d].pk and c.name not in seen})
        parts = []
        for d in desc:
            dt = s.tables[d]
            have = {c.name for c in dt.columns}
            sel = [f"{_q(dt.pk[0])} AS __ID", f"'{vkg_build.class_name(d)}' AS __CLS"]
            sel += [f"{_q(c)} AS {_q(c)}" if c in have else f"NULL AS {_q(c)}" for c in extra]
            parts.append(f"SELECT {', '.join(sel)} FROM {_q(src)}.{_q(d)}")
        agg = ", ".join([f"string_agg(__CLS, ',' ORDER BY __CLS) AS SUBCLASSES"] +
                        [f"max({_q(c)}) AS {_q(c)}" for c in extra])
        joins.append(f"LEFT JOIN (SELECT __ID, {agg} FROM ({' UNION ALL '.join(parts)}) GROUP BY __ID) d "
                     f"ON d.__ID = t.{_q(pk)}")
        cols += ["d.SUBCLASSES"] + [f"d.{_q(c)}" for c in extra]
    return f"SELECT {', '.join(cols)} FROM {_q(src)}.{_q(table)} t " + " ".join(joins)


def build_instance(con, src: str, h: Hierarchy) -> dict:
    dst = f"{src}_L15"
    con.execute(f"CREATE SCHEMA IF NOT EXISTS {_q(dst)}")
    for table in h.s.tables:
        con.execute(f"CREATE OR REPLACE VIEW {_q(dst)}.{_q(table)} AS {view_sql(h, table, src)}")
    return check_instance(con, src, h)


def check_instance(con, src: str, h: Hierarchy) -> dict:
    dst = f"{src}_L15"
    bad = []
    for table in h.s.tables:
        n_t = con.execute(f"SELECT count(*) FROM {_q(src)}.{_q(table)}").fetchone()[0]
        n_v = con.execute(f"SELECT count(*) FROM {_q(dst)}.{_q(table)}").fetchone()[0]
        if n_t != n_v:
            bad.append({"view": table, "table_rows": n_t, "view_rows": n_v})
    supers = [t for t in h.s.tables if h.children.get(t)]
    for sup in supers:
        got = dict(con.execute(
            f"SELECT c, count(*) FROM (SELECT unnest(string_split(SUBCLASSES, ',')) AS c "
            f"FROM {_q(dst)}.{_q(sup)} WHERE SUBCLASSES IS NOT NULL) GROUP BY c").fetchall())
        for d in h.subtree(sup) - {sup}:
            # a subclass row whose parent row is missing would not appear; Gate 1 forbids that
            n_d = con.execute(f"SELECT count(*) FROM {_q(src)}.{_q(d)}").fetchone()[0]
            if got.get(vkg_build.class_name(d), 0) != n_d:
                bad.append({"view": sup, "subclass": d, "table_rows": n_d,
                            "members": got.get(vkg_build.class_name(d), 0)})
    return {"instance": src, "views": len(h.s.tables), "flattened": len(supers), "mismatches": bad}


def build() -> dict:
    from ..load_fiben import connect
    h = Hierarchy(schema.load())
    con = connect(read_only=False)
    res = [build_instance(con, src, h) for src in present_instances(con)]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "views.sql").write_text(
        "-- L1.5 hierarchy-flattened views (generated by nl2q.evalkit.l15; do not edit)\n" +
        "\n".join(f'CREATE VIEW "{paths.SCHEMA}_L15"."{t}" AS {view_sql(h, t, paths.SCHEMA)};'
                  for t in h.s.tables), encoding="utf-8")
    out = {"instances": res, "ok": all(not r["mismatches"] for r in res)}
    (OUT / "check.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    return out


if __name__ == "__main__":
    o = build()
    for r in o["instances"]:
        print(f"{r['instance']}_L15: {r['views']} views, {r['flattened']} flattened hierarchies, "
              f"{len(r['mismatches'])} mismatches")
    print("ok" if o["ok"] else "MISMATCH")
