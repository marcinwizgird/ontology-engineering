-- FIBEN 10-table slice (spec section 2). Quoted upper-case identifiers, as the R2RML
-- mappings reference them ("PUBLIC"."COMPANY"). Portable: PostgreSQL and DuckDB.
CREATE SCHEMA IF NOT EXISTS "PUBLIC";

CREATE TABLE "PUBLIC"."COMPANY" (
    "COMP_ID"      INTEGER PRIMARY KEY,
    "COMP_NAME"    VARCHAR(200) NOT NULL,
    "CIK_CODE"     VARCHAR(10),
    "SIC_CODE"     VARCHAR(4),
    "COUNTRY_INC"  VARCHAR(2)
);

CREATE TABLE "PUBLIC"."EXCHANGE" (
    "EXCH_ID"      INTEGER PRIMARY KEY,
    "EXCH_SYMBOL"  VARCHAR(10) NOT NULL,
    "EXCH_NAME"    VARCHAR(100),
    "COUNTRY"      VARCHAR(2)
);

CREATE TABLE "PUBLIC"."SECURITY" (
    "SEC_ID"         INTEGER PRIMARY KEY,
    "ISSUER_COMP_ID" INTEGER NOT NULL REFERENCES "PUBLIC"."COMPANY" ("COMP_ID"),
    "EXCH_ID"        INTEGER REFERENCES "PUBLIC"."EXCHANGE" ("EXCH_ID"),
    "SYMBOL"         VARCHAR(12),
    "SEC_NAME"       VARCHAR(200),
    "SEC_TYPE"       VARCHAR(5) NOT NULL,
    "LAST_PRICE"     DECIMAL(18, 4)
);

CREATE TABLE "PUBLIC"."STOCK" (
    "SEC_ID"             INTEGER PRIMARY KEY REFERENCES "PUBLIC"."SECURITY" ("SEC_ID"),
    "SHARES_OUTSTANDING" BIGINT,
    "DIVIDEND_YIELD"     DECIMAL(9, 4),
    "PE_RATIO"           DECIMAL(9, 2)
);

CREATE TABLE "PUBLIC"."BOND" (
    "SEC_ID"        INTEGER PRIMARY KEY REFERENCES "PUBLIC"."SECURITY" ("SEC_ID"),
    "COUPON_RATE"   DECIMAL(9, 4),
    "MATURITY_DATE" DATE,
    "CREDIT_RATING" VARCHAR(5)
);

CREATE TABLE "PUBLIC"."CUSTOMER" (
    "CUST_ID"    INTEGER PRIMARY KEY,
    "FULL_NAME"  VARCHAR(200) NOT NULL,
    "CUST_TYPE"  VARCHAR(6) NOT NULL,
    "TAX_ID"     VARCHAR(20),
    "DOMICILE"   VARCHAR(2)
);

CREATE TABLE "PUBLIC"."ACCOUNT" (
    "ACC_ID"       INTEGER PRIMARY KEY,
    "CUST_ID"      INTEGER NOT NULL REFERENCES "PUBLIC"."CUSTOMER" ("CUST_ID"),
    "ACC_NUMBER"   VARCHAR(20) NOT NULL,
    "ACC_STATUS"   VARCHAR(10),
    "CURRENCY"     VARCHAR(3),
    "CASH_BALANCE" DECIMAL(18, 2)
);

CREATE TABLE "PUBLIC"."HOLDING" (
    "HOLDING_ID"     INTEGER PRIMARY KEY,
    "ACC_ID"         INTEGER NOT NULL REFERENCES "PUBLIC"."ACCOUNT" ("ACC_ID"),
    "SEC_ID"         INTEGER NOT NULL REFERENCES "PUBLIC"."SECURITY" ("SEC_ID"),
    "QUANTITY"       DECIMAL(18, 4),
    "PURCHASE_PRICE" DECIMAL(18, 4),
    "VALUATION_DATE" DATE
);

CREATE TABLE "PUBLIC"."TRADE_ORDER" (
    "ORDER_ID"    INTEGER PRIMARY KEY,
    "ACC_ID"      INTEGER NOT NULL REFERENCES "PUBLIC"."ACCOUNT" ("ACC_ID"),
    "SEC_ID"      INTEGER NOT NULL REFERENCES "PUBLIC"."SECURITY" ("SEC_ID"),
    "ORDER_TYPE"  VARCHAR(4) NOT NULL,
    "ORDER_QTY"   DECIMAL(18, 4),
    "LIMIT_PRICE" DECIMAL(18, 4),
    "TRADE_DATE"  DATE
);

CREATE TABLE "PUBLIC"."FIN_REPORT" (
    "REPORT_ID"        INTEGER PRIMARY KEY,
    "COMP_ID"          INTEGER NOT NULL REFERENCES "PUBLIC"."COMPANY" ("COMP_ID"),
    "FISCAL_YEAR"      INTEGER NOT NULL,
    "FISCAL_PERIOD"    VARCHAR(3),
    "REVENUE_USD"      DECIMAL(20, 2),
    "NET_INCOME_USD"   DECIMAL(20, 2),
    "TOTAL_ASSETS_USD" DECIMAL(20, 2)
);
