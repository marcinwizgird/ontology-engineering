BY_NAME = {a.name: a for a in CORPUS}


def get(name: str) -> Artefact:
    return BY_NAME[name]


def verify_corpus() -> list[str]:
    """Check every detector against the hand-authored labels.

    Returns a list of human-readable disagreements; empty means the corpus and
    the detectors agree. Notebooks run this as a self-test.
    """
    from oe_course import ontology as ont

    problems: list[str] = []
    for art in CORPUS:
        g = ont.load_graph(art.turtle)
        level = ont.classify_spectrum(g)["level"]
        if level != art.gold_level:
            problems.append(f"{art.name}: level detected {level!r}, gold {art.gold_level!r}")
        detected = set(ont.smell_summary(g)) - set(art.tolerated_smells)
        if detected != set(art.gold_smells):
            missing = set(art.gold_smells) - detected
            extra = detected - set(art.gold_smells)
            problems.append(
                f"{art.name}: smells missing={sorted(missing)} unexpected={sorted(extra)}"
            )
    return problems
