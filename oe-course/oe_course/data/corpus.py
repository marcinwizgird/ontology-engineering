"""A labelled corpus of small ontologies — the course's evaluation substrate.

Each entry carries **hand-authored** gold labels: the spectrum level the author
intended and the modelling defects the author deliberately injected. The labels
are *not* generated by the detectors in :mod:`oe_course.ontology`; instead
:func:`verify_corpus` checks that the detectors agree with the author, so a
regression in either the corpus or a detector shows up immediately.

This matters for what the Chapter 1 agent evaluation actually measures. The
deterministic metric asks "did the agent gather the right evidence and report it
faithfully?" — a tool-using agent's real job — while the LLM judge scores the
quality of the written justification. Keeping the gold independent of the
detectors keeps that first question honest.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent

_HEADER = """@prefix owl:  <http://www.w3.org/2002/07/owl#> .
@prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix skos: <http://www.w3.org/2004/02/skos/core#> .
@prefix ex:   <http://example.org/oe/> .
"""


@dataclass(frozen=True)
class Artefact:
    """One labelled ontology in the corpus."""

    name: str
    turtle: str
    gold_level: str
    gold_smells: frozenset[str]
    note: str = ""
    #: Detectors whose findings are expected but not part of the graded label
    #: (e.g. a vocabulary that legitimately has no properties to annotate).
    tolerated_smells: frozenset[str] = field(default_factory=frozenset)


def _ttl(body: str) -> str:
    return _HEADER + body


