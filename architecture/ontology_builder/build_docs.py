# FEATURE_EXTRACTION.md
# --------------------------------------------------------------------------- #
def feature_extraction_md() -> str:
    L: list[str] = [BANNER, "", "# Ontology Builder — Feature Extraction", ""]
    L.append(
        "Every feature below was read out of the reference platforms' **source "
        "code**, not their marketing material. Each carries the exact service, "
        "handler, enum or extension point it came from, so the port can be "
        "checked against the original."
    )
    L.append("")
    L.append(
        f"**Totals:** {len(fm.FEATURES)} features across {len(fm.FEATURE_AREAS)} "
        f"areas, mapping to {len(fm.covered_capabilities())} of "
        f"{len(CAPABILITY_BY_ID)} capabilities in the Ontology Engineering "
        "Capability Model."
    )
    L.append("")

    # -- sources ---------------------------------------------------------- #
    L.append("## 1. Sources")
    L.append("")
    L.append("| ID | Platform | Repository | Stack | Licence |")
    L.append("|---|---|---|---|---|")
    for t in fm.SOURCE_TOOLS:
        L.append(f"| `{t.id}` | **{t.name}** | `{t.repo}` | {t.stack} | {t.licence} |")
    L.append("")
    for t in fm.SOURCE_TOOLS:
        L.append(f"**{t.name}.** {t.notes}")
        L.append("")

    # -- extraction statistics -------------------------------------------- #
    L.append("### What the extraction covered")
    L.append("")
    L.append(
        "| Platform | Surface measured | Count |\n"
        "|---|---|---|\n"
        "| VocBench 3 | Angular service classes mirroring the Semantic Turkey API | 60 |\n"
        "| VocBench 3 | distinct server operations | **781** |\n"
        "| VocBench 3 | guarded actions in `AuthorizationEvaluator` | **330** |\n"
        "| VocBench 3 | capability areas (`rdf`, `pm`, `cform`, `sys`, `rbac`, "
        "`customService`, `invokableReporter`) | 7 |\n"
        "| VocBench 3 | extension points | 15 |\n"
        "| VocBench 3 | resource-view sections | 30 |\n"
        "| VocBench 3 | integrity-constraint checks | 38 |\n"
        "| WebProtégé | action handlers | **145** |\n"
        "| WebProtégé | built-in capabilities | 53 |\n"
        "| WebProtégé | built-in roles (inheriting) | 15 |\n"
        "| WebProtégé | microservice repositories | ~15 |\n"
        "| Protégé Desktop | OSGi extension points | 24 |\n"
        "| Protégé Desktop | workspace tabs | 7 |\n"
        "| Protégé Desktop | view components | 51 |\n"
        "| Protégé Desktop | menu actions | 132 |"
    )
    L.append("")
    L.append(
        "> The Semantic Turkey **server** repository "
        "(`bitbucket.org/art-uniroma2/semanticturkey`) is not publicly clonable — "
        "it demands Bitbucket credentials. Its contract was therefore recovered "
        "in full from the VocBench 3 client, which mirrors it operation by "
        "operation, plus the peer-reviewed architecture description in the "
        "Semantic Web Journal paper. Nothing in this document depends on "
        "server-side code that was not observable."
    )
    L.append("")

    # -- source → feature coverage ---------------------------------------- #
    L.append("### Where each feature came from")
    L.append("")
    counts = {t.id: len(fm.features_from_source(t.id)) for t in fm.SOURCE_TOOLS}
    only = Counter()
    for f in fm.FEATURES:
        tools = {e.split(":", 1)[0] for e in f.evidence} & set(fm.SOURCE_TOOL_BY_ID)
        if len(tools) == 1:
            only[next(iter(tools))] += 1
        elif not tools:
            only["(new)"] += 1
    L.append("| Platform | Features drawing on it | Features drawing on it *alone* |")
    L.append("|---|---|---|")
    for t in fm.SOURCE_TOOLS:
        L.append(f"| {t.name} | {counts[t.id]} | {only[t.id]} |")
    L.append(
        f"| *(no reference tool — added here)* | {only['(new)']} | {only['(new)']} |")
    L.append("")

    # -- areas ------------------------------------------------------------ #
    L.append("## 2. Feature areas")
    L.append("")
    L.append("| Area | Name | Backend package | Features |")
    L.append("|---|---|---|---|")
    for a in fm.FEATURE_AREAS:
        L.append(f"| `{a.id}` | {a.name} | `{a.package}` | "
                 f"{len(fm.features_in_area(a.id))} |")
    L.append("")

    # -- the catalogue ---------------------------------------------------- #
    L.append("## 3. Feature catalogue")
    L.append("")
    for a in fm.FEATURE_AREAS:
        feats = fm.features_in_area(a.id)
        if not feats:
            continue
        L.append(f"### {a.id} · {a.name}")
        L.append("")
        L.append(f"*{a.description}*  ·  Backend package `{a.package}`")
        L.append("")
        for f in feats:
            L.append(f"#### {f.id} · {f.name}  `[{f.priority}]` `[{f.phase}]`")
            L.append("")
            L.append(f.description)
            L.append("")
            L.append(f"- **Source evidence:** {_evidence_md(f)}")
            L.append("- **Capabilities:** "
                     + ", ".join(_cap(c) for c in f.capabilities))
            L.append(f"- **Layers:** {', '.join(f.layers)}")
            L.append(f"- **Target:** `{f.target}`")
            if f.depends_on:
                L.append("- **Depends on:** " + ", ".join(f"`{d}`" for d in f.depends_on))
            if f.reuse:
                L.append("- **Reuse existing:** "
                         + ", ".join(f"`{r}`" for r in f.reuse))
            if f.notes:
                L.append(f"- **Note:** {f.notes}")
            L.append("")

    # -- gaps ------------------------------------------------------------- #
    L.append("## 4. Gaps in all three reference platforms")
    L.append("")
    L.append(
        "Features with no reference-tool evidence — where the merged product must "
        "be better than everything it merges:"
    )
    L.append("")
    L.append("| Feature | Why none of the three has it |")
    L.append("|---|---|")
    for f in fm.FEATURES:
        tools = {e.split(":", 1)[0] for e in f.evidence} & set(fm.SOURCE_TOOL_BY_ID)
        if tools:
            continue
        L.append(f"| **{f.id}** {f.name} | {f.notes or f.description} |")
    L.append("")
    return "\n".join(L) + "\n"


