# CAPABILITY_MAPPING.md
# --------------------------------------------------------------------------- #
def capability_mapping_md() -> str:
    L: list[str] = [BANNER, "", "# Ontology Builder — Capability Mapping", ""]
    L.append(
        "How the extracted VocBench 3, WebProtégé and Protégé Desktop features map "
        "onto the **Ontology Engineering Capability Model** "
        "(`ontology_engineering_capabilities/`), and therefore onto the **EKGF "
        "EKG Maturity Model** levels the platform is being built to reach."
    )
    L.append("")

    covered = fm.covered_capabilities()
    uncovered = sorted(set(CAPABILITY_BY_ID) - covered)
    L.append(
        f"**Coverage:** {len(covered)} of {len(CAPABILITY_BY_ID)} capabilities are "
        f"realised by at least one Ontology Builder feature."
    )
    L.append("")

    # -- level view ------------------------------------------------------- #
    L.append("## 1. Coverage by EKGF maturity level")
    L.append("")
    L.append("| Level | Capabilities | Realised | Features | Phases involved |")
    L.append("|---|---|---|---|---|")
    for lvl, lname in EKGF_LEVELS.items():
        caps = [c for c in CAPABILITY_BY_ID.values() if c.maturity_level == lvl]
        real = [c for c in caps if c.id in covered]
        feats = {f.id for c in real for f in fm.features_for_capability(c.id)}
        phases = sorted({fm.FEATURE_BY_ID[i].phase for i in feats})
        L.append(f"| **L{lvl} {lname}** | {len(caps)} | {len(real)} | "
                 f"{len(feats)} | {', '.join(phases) or '—'} |")
    L.append("")
    L.append(
        "The Level-2 (*Extensible Platform*) target of the existing application "
        "architecture (`architecture/ARCHITECTURE.md`) is met in full by phases "
        "**P0–P4**. Phases **P5–P8** carry the platform into L3–L5."
    )
    L.append("")

    # -- capability → features -------------------------------------------- #
    L.append("## 2. Capability → Ontology Builder features")
    L.append("")
    for domain in ("Business", "Technology"):
        L.append(f"### {domain} capabilities")
        L.append("")
        cats = [c for c in CATEGORY_BY_ID.values() if c.domain == domain]
        for cat in cats:
            caps = [c for c in CAPABILITY_BY_ID.values() if c.category == cat.id]
            if not caps:
                continue
            L.append(f"#### {cat.id} · {cat.name}")
            L.append("")
            L.append("| Capability | Target | Realising features | Earliest phase |")
            L.append("|---|---|---|---|")
            for c in caps:
                feats = fm.features_for_capability(c.id)
                ids = ", ".join(f"`{f.id}`" for f in feats) or "*—*"
                ph = min((f.phase for f in feats), default="—")
                L.append(f"| **{c.id}** {c.name} | L{c.maturity_level} | {ids} | {ph} |")
            L.append("")

    # -- uncovered -------------------------------------------------------- #
    L.append("## 3. Capabilities deliberately out of scope")
    L.append("")
    if uncovered:
        L.append(
            "These are realised by enterprise systems the Ontology Builder should "
            "integrate with, not replace — consistent with `architecture/"
            "ARCHITECTURE.md`, which already assigns them to COTS components "
            "(`C.FUND` Portfolio & Funding Management, `C.SKILL` Skills & Talent "
            "Management)."
        )
        L.append("")
        L.append("| Capability | Target level | Realised instead by |")
        L.append("|---|---|---|")
        hint = {
            "B.SG.4": "Portfolio/PPM tooling; the Builder contributes project "
                      "inventory and effort signals via `OB.PRJ.06` / `OB.PRJ.10`.",
            "B.VP.1": "Benefits-tracking in the enterprise's own value framework; "
                      "the Builder contributes usage and quality KPIs "
                      "(`OB.PRJ.10`, `OB.QLT.04`).",
        }
        for cid in uncovered:
            c = CAPABILITY_BY_ID[cid]
            L.append(f"| **{cid}** {c.name} | L{c.maturity_level} | "
                     f"{hint.get(cid, 'External system.')} |")
        L.append("")

    # -- feature → capability --------------------------------------------- #
    L.append("## 4. Ontology Builder features → capabilities")
    L.append("")
    L.append("| Feature | Area | Phase | Prio | Capabilities |")
    L.append("|---|---|---|---|---|")
    for f in fm.FEATURES:
        L.append(f"| **{f.id}** {f.name} | {f.area} | {f.phase} | {f.priority} | "
                 + ", ".join(f.capabilities) + " |")
    L.append("")

    # -- phase view -------------------------------------------------------- #
    L.append("## 5. What each phase unlocks")
    L.append("")
    for ph, title in fm.PHASES.items():
        feats = fm.features_in_phase(ph)
        caps = sorted({c for f in feats for c in f.capabilities})
        newly = [c for c in caps
                 if all(fm.FEATURE_BY_ID[g.id].phase >= ph
                        for g in fm.features_for_capability(c))]
        L.append(f"### {ph} — {title}")
        L.append("")
        L.append(f"- **Features:** {len(feats)} "
                 f"({sum(1 for f in feats if f.priority == 'MUST')} MUST)")
        L.append("- **Capabilities first touched here:** "
                 + (", ".join(newly) if newly else "*(deepens earlier ones)*"))
        L.append("")
    return "\n".join(L) + "\n"


