"""Regenerate the Ontology Builder's generated documents from ``feature_model``.

Outputs (all beside this script):

* ``FEATURE_EXTRACTION.md`` — the extracted feature inventory, by area, with the
  source evidence for every feature.
* ``CAPABILITY_MAPPING.md`` — the two-way mapping between features and the
  Ontology Engineering Capability Model, plus coverage analysis per EKGF level.
* ``artifacts/feature_phases.mmd`` — Mermaid view of the phase plan.
* ``artifacts/feature_capability_map.mmd`` — Mermaid view of area → capability.

Usage::

    PYTHONPATH=. python architecture/ontology_builder/build_docs.py
"""

from __future__ import annotations

import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
for p in (ROOT, HERE):
    if p not in sys.path:
        sys.path.insert(0, p)

import feature_model as fm  # noqa: E402
from ontology_engineering_capabilities.capability_model import (  # noqa: E402
    CAPABILITY_BY_ID,
    CATEGORY_BY_ID,
    EKGF_LEVELS,
)

BANNER = "<!-- GENERATED by architecture/ontology_builder/build_docs.py — do not edit by hand. -->"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def _cap(cid: str) -> str:
    c = CAPABILITY_BY_ID.get(cid)
    return f"{cid} {c.name}" if c else cid


def _evidence_md(feature: fm.Feature) -> str:
    out = []
    for e in feature.evidence:
        tool, _, rest = e.partition(":")
        if tool in fm.SOURCE_TOOL_BY_ID:
            out.append(f"**{tool}** · {rest.strip()}")
        else:
            out.append(e)
    return "<br>".join(out)


