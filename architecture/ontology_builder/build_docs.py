# Mermaid artifacts
# --------------------------------------------------------------------------- #
def phases_mmd() -> str:
    L = ["flowchart LR"]
    for ph, title in fm.PHASES.items():
        feats = fm.features_in_phase(ph)
        L.append(f'  {ph}["{ph}<br/>{title.split(" — ")[0]}<br/>'
                 f'{len(feats)} features"]')
    keys = list(fm.PHASES)
    for a, b in zip(keys, keys[1:]):
        L.append(f"  {a} --> {b}")
    return "\n".join(L) + "\n"


def area_capability_mmd() -> str:
    L = ["flowchart LR"]
    seen_caps: set[str] = set()
    edges: set[tuple[str, str]] = set()
    for a in fm.FEATURE_AREAS:
        L.append(f'  A{a.id}["{a.id} {a.name}"]')
        for f in fm.features_in_area(a.id):
            for c in f.capabilities:
                edges.add((a.id, c))
                seen_caps.add(c)
    for c in sorted(seen_caps):
        cap = CAPABILITY_BY_ID[c]
        cid = c.replace(".", "_")
        L.append(f'  C{cid}(["{c}<br/>{cap.name}<br/>L{cap.maturity_level}"])')
    for a, c in sorted(edges):
        L.append(f"  A{a} --> C{c.replace('.', '_')}")
    return "\n".join(L) + "\n"


# --------------------------------------------------------------------------- #
def main() -> None:
    try:
        problems = fm.validate_model(set(CAPABILITY_BY_ID))
    except Exception as exc:  # pragma: no cover
        raise SystemExit(f"model validation failed: {exc}")
    if problems:
        for p in problems:
            print("PROBLEM:", p)
        raise SystemExit("feature model is inconsistent — refusing to generate")

    art = os.path.join(HERE, "artifacts")
    os.makedirs(art, exist_ok=True)

    outputs = {
        os.path.join(HERE, "FEATURE_EXTRACTION.md"): feature_extraction_md(),
        os.path.join(HERE, "CAPABILITY_MAPPING.md"): capability_mapping_md(),
        os.path.join(art, "feature_phases.mmd"): phases_mmd(),
        os.path.join(art, "feature_capability_map.mmd"): area_capability_mmd(),
    }
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(text):,} chars)")

    print(f"\nfeatures {len(fm.FEATURES)} | areas {len(fm.FEATURE_AREAS)} | "
          f"capabilities covered {len(fm.covered_capabilities())}"
          f"/{len(CAPABILITY_BY_ID)} | model problems 0")


if __name__ == "__main__":
    main()
