"""The YAML mapping spec: a reviewable text form of a mapping, for git and code review.

The format is the SPARQL-2-SQL PoC's ``mapping-spec.yaml`` (``base_iri``, ``schema``,
``prefixes``, ``entities``, ``maps``), so that file and its generator retire into SIP.
It is an *exchange* format, not a second source of truth: importing compiles every map
through :mod:`.patterns` into ordinary triples maps, and exporting lifts the stored maps
back. A map no pattern reproduces cannot be written as spec; it is returned in
``custom`` (R2RML dict form) instead of being dropped.

PyYAML is optional: :func:`load_spec` / :func:`dump_spec` import it when called and say
so when it is missing. Everything else works on the parsed dict.

:func:`render_r2rml` writes the compact Turtle the PoC generator writes (one line per
predicate-object map, blank nodes, relative ``<#id>`` map IRIs), byte for byte.
"""

from __future__ import annotations

import re
from typing import Callable

from .patterns import EntityDef, PatternError, compile_map, lift
from .r2rml import TriplesMap

__all__ = ["SpecError", "load_spec", "dump_spec", "validate_spec", "spec_entities",
           "spec_maps", "compile_spec", "maps_to_spec", "render_r2rml"]

_MAP_FIELDS = {"id", "table", "schema", "subject", "subject_column", "class", "filter",
               "properties"}
_PROP_FIELDS = {"predicate", "column", "datatype", "ref"}

HEADER = "# Generated by SIP (mapping.exportSpec / vkg.spec.render_r2rml). Do not edit by hand.\n"


class SpecError(ValueError):
    pass


def _yaml():
    try:
        import yaml
    except ImportError:
        raise SpecError("the YAML spec needs the optional PyYAML package "
                        "(pip install pyyaml); the dict form works without it") from None
    return yaml


def load_spec(text: str) -> dict:
    spec = _yaml().safe_load(text)
    validate_spec(spec)
    return spec


def dump_spec(spec: dict) -> str:
    yaml = _yaml()

    class _Dumper(yaml.SafeDumper):
        pass

    def _flow(d, data):        # property dicts on one line, as the PoC writes them
        return d.represent_mapping("tag:yaml.org,2002:map", data, flow_style=True)

    class _Prop(dict):
        pass
    _Dumper.add_representer(_Prop, _flow)
    out = dict(spec)
    out["maps"] = [dict(m, properties=[_Prop(p) for p in m["properties"]])
                   if m.get("properties") else m for m in spec.get("maps", [])]
    return yaml.dump(out, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def validate_spec(spec: dict) -> None:
    """Structural checks (the PoC generator's); every problem is reported at once."""
    if not isinstance(spec, dict):
        raise SpecError("a mapping spec is a mapping (dict)")
    errors: list[str] = []
    prefixes, entities = spec.get("prefixes") or {}, spec.get("entities") or {}
    for key in ("base_iri", "prefixes", "entities", "maps"):
        if key not in spec:
            errors.append(f"missing top-level key '{key}'")

    def curie(where: str, value) -> None:
        if not isinstance(value, str) or ":" not in value:
            errors.append(f"{where}: '{value}' is not a prefixed name")
        elif value.split(":", 1)[0] not in prefixes and not value.startswith(("http", "urn:")):
            errors.append(f"{where}: unknown prefix in '{value}'")

    paths = [e.get("path") for e in entities.values()]
    if len(paths) != len(set(paths)):
        errors.append("entities: two entities share an IRI path")
    for name, e in entities.items():
        for k in ("path", "table", "key"):
            if k not in e:
                errors.append(f"entity '{name}': missing '{k}'")
    ids = [m.get("id") for m in spec.get("maps") or []]
    for dup in sorted({i for i in ids if ids.count(i) > 1}):
        errors.append(f"map id '{dup}' is used more than once")
    for m in spec.get("maps") or []:
        where = f"map '{m.get('id', '?')}'"
        if extra := set(m) - _MAP_FIELDS:
            errors.append(f"{where}: unknown fields {sorted(extra)}")
        for k in ("id", "table", "subject"):
            if k not in m:
                errors.append(f"{where}: missing '{k}'")
        if m.get("subject") not in entities:
            errors.append(f"{where}: unknown subject entity '{m.get('subject')}'")
        if "class" in m:
            curie(where, m["class"])
        if not m.get("class") and not m.get("properties"):
            errors.append(f"{where}: produces no triples (no class and no properties)")
        for i, p in enumerate(m.get("properties") or [], 1):
            pw = f"{where} property {i}"
            if extra := set(p) - _PROP_FIELDS:
                errors.append(f"{pw}: unknown fields {sorted(extra)}")
            curie(pw, p.get("predicate"))
            if "ref" in p:
                if p["ref"] not in entities:
                    errors.append(f"{pw}: unknown ref entity '{p['ref']}'")
                if "datatype" in p:
                    errors.append(f"{pw}: a ref produces an IRI and takes no datatype")
            elif "column" not in p:
                errors.append(f"{pw}: needs 'column' (literal) or 'ref' (link)")
            if "datatype" in p:
                curie(pw, p["datatype"])
    if errors:
        raise SpecError("mapping spec is invalid:\n  " + "\n  ".join(errors))


# --------------------------------------------------------------------------- #
# spec <-> pattern parameters
# --------------------------------------------------------------------------- #

def _expand(prefixes: dict) -> Callable[[str], str]:
    def f(x: str) -> str:
        if x.startswith(("http://", "https://", "urn:")):
            return x
        p, _, local = x.partition(":")
        if p not in prefixes:
            raise SpecError(f"unknown prefix in {x!r}")
        return prefixes[p] + local
    return f


def _compact(prefixes: dict) -> Callable[[str], str]:
    by_len = sorted(prefixes.items(), key=lambda kv: -len(kv[1]))

    def f(iri: str) -> str:
        for p, ns in by_len:
            if iri.startswith(ns) and re.fullmatch(r"[A-Za-z0-9_.-]*", iri[len(ns):]):
                return f"{p}:{iri[len(ns):]}"
        return iri
    return f


def spec_entities(spec: dict) -> dict[str, EntityDef]:
    return {name: EntityDef(name, e["path"], e["table"], e["key"], e.get("base",
                                                                         spec["base_iri"]))
            for name, e in spec["entities"].items()}


def spec_maps(spec: dict) -> list[dict]:
    """The spec's maps as pattern parameters (CURIEs expanded to IRIs)."""
    ex = _expand(spec.get("prefixes") or {})
    out = []
    for m in spec["maps"]:
        d = {k: v for k, v in m.items() if k != "properties"}
        if d.get("class"):
            d["class"] = ex(d["class"])
        if m.get("properties"):
            d["properties"] = [dict(p, predicate=ex(p["predicate"]),
                                    **({"datatype": ex(p["datatype"])} if "datatype" in p
                                       else {})) for p in m["properties"]]
        out.append(d)
    return out


def compile_spec(spec: dict, *, mint: Callable[[str], str] = lambda i: f"#{i}"
                 ) -> tuple[dict[str, EntityDef], list[TriplesMap]]:
    """Entities and triples maps of a spec (structure validated first)."""
    validate_spec(spec)
    ents = spec_entities(spec)
    try:
        maps = [compile_map(m, ents, schema=spec.get("schema"), mint=mint)
                for m in spec_maps(spec)]
    except PatternError as e:
        raise SpecError(str(e)) from None
    return ents, maps


def maps_to_spec(maps: list[TriplesMap], entities: dict[str, EntityDef], *, base_iri: str,
                 prefixes: dict[str, str], schema: str | None = None) -> dict:
    """Lift *maps* into a spec dict. Maps no pattern reproduces go to ``custom``."""
    co = _compact(prefixes)
    spec: dict = {"base_iri": base_iri}
    if schema:
        spec["schema"] = schema
    spec["prefixes"] = dict(prefixes)
    spec["entities"] = {}
    for name, e in sorted(entities.items()):
        d = {"path": e.path, "table": e.table, "key": e.key[0] if len(e.key) == 1 else e.key}
        if e.base != base_iri:
            d["base"] = e.base
        spec["entities"][name] = d
    spec["maps"], custom = [], []
    for tm in maps:
        got = lift(tm, entities, schema=schema)
        if got is None:
            custom.append(tm.as_dict())
            continue
        m = {k: v for k, v in got[1].items() if k not in ("iri", "source", "label")}
        if m.get("class"):
            m["class"] = co(m["class"])
        for p in m.get("properties", []):
            p["predicate"] = co(p["predicate"])
            if "datatype" in p:
                p["datatype"] = co(p["datatype"])
        order = ["id", "table", "schema", "filter", "subject", "subject_column", "class",
                 "properties"]
        spec["maps"].append({k: m[k] for k in order if k in m})
    if custom:
        spec["custom"] = custom
    return spec


# --------------------------------------------------------------------------- #
# compact Turtle (the PoC generator's rendering)
# --------------------------------------------------------------------------- #

def _lit(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_r2rml(spec: dict, header: str = HEADER) -> str:
    """The spec as compact R2RML Turtle with ``<#id>`` map IRIs and blank nodes."""
    ents, maps = compile_spec(spec)
    co = _compact(spec.get("prefixes") or {})

    def term(iri: str) -> str:
        c = co(iri)
        return c if c != iri else f"<{iri}>"
    out = [header]
    out += [f"@prefix {p}: <{iri}> ." for p, iri in (spec.get("prefixes") or {}).items()]
    for m, tm in zip(spec["maps"], maps):
        lt = (f"rr:tableName {_lit(tm.table_name)}" if tm.table_name
              else f"rr:sqlQuery {_lit(tm.sql_query)}")
        lines = [f"<#{m['id']}> a rr:TriplesMap ;", f"    rr:logicalTable [ {lt} ] ;"]
        subject = f"rr:template {_lit(tm.subject.template)}"
        if tm.classes:
            subject += f" ; rr:class {term(tm.classes[0])}"
        lines.append(f"    rr:subjectMap [ {subject} ] ;")
        poms = {(p.predicate, p.object.template or p.object.column): p for p in tm.poms}
        for p in spec_maps({"prefixes": spec.get("prefixes"), "maps": [m]})[0].get(
                "properties", []):
            if "ref" in p:
                obj = ents[p["ref"]].template(p.get("column"))
                om = f"rr:template {_lit(obj)}"
            else:
                pm = poms[(p["predicate"], '"' + p["column"].replace('"', '""') + '"')]
                om = f"rr:column {_lit(pm.object.column)}"
                if pm.object.datatype:
                    om += f" ; rr:datatype {term(pm.object.datatype)}"
            lines.append(f"    rr:predicateObjectMap [ rr:predicate {term(p['predicate'])} ; "
                         f"rr:objectMap [ {om} ] ] ;")
        lines[-1] = lines[-1][:-2] + " ."
        out += ["", *lines]
    return "\n".join(out) + "\n"
